'use strict';
// Exercise the final indexed archive, not only the intermediate HUD bundle.
// Supply the inspected retail inputs separately; no game files are distributed.
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const native = path.resolve(process.env.NATIVE_ASSETS || path.join(__dirname, 'payload/resources/native'));
const app = path.resolve(process.env.PACKAGED_APP || path.join(__dirname, 'app'));
const retail = path.resolve(process.env.RETAIL_INPUTS || path.join(__dirname, '../orion-base/retail'));
const ui = require(native + '/lobby/supcom2-ui.cjs');
const builder = require(native + '/lobby/indexed-probe.cjs');
const { patchFor } = require(app + '/dist/node/server/gameplay.js');
const { rulesetFor } = require(app + '/dist/node/server/research-publication.js');
const inputs = ['ui.scd', 'toc.win.bdf', 'ui.scd.enc'].map(name => fs.readFileSync(path.join(retail, name)));
const hud = fs.readFileSync(path.join(retail, 'lua.scd'));
const art = native + '/lobby/art';
const textures = require(art + '/art-manifest.json').textures.map(t => ({
    name: 'textures/ui/common/pc/frontend/' + t.name,
    data: fs.readFileSync(path.join(art, t.name))
}));
const draft = structuredClone(require(app + '/dist/node/server/data/research-retail.json').draft);
draft.title = 'Archive regression research';
draft.nodes.find(n => n.id === 'ULB_RANGE').cost += 1;
const research = rulesetFor(draft);

function build(profileId, scale, rules) {
    const gameplay = patchFor(profileId, '1.0.0', rules, undefined, process.env.AI_REVISION);
    const result = builder.build(...inputs, {
        layout: true, textures, hud, hudScale: scale, playerBadges: true,
        gameplay, ...(rules ? { research: rules } : {})
    });
    const entries = ui.readZip(result.archive, 4096, profileId === 'reforged-balance');
    const expanded = entries.reduce((n, entry) => n + entry.data.length, 0);
    assert.ok(result.archive.length < 144 * 1024 * 1024);
    assert.equal(result.manifest.hud.gameplay.profileId, profileId);
    if (rules) assert.equal(result.manifest.hud.researchId, rules.id);
    console.log('Final archive passed', JSON.stringify({profileId, scale, research: !!rules,
        compressed: result.archive.length, expanded, entries: entries.length}));
    return { result, entries, expanded };
}

const full = build('reforged-balance', 1.125);
assert.ok(full.expanded > 448 * 1024 * 1024, 'Fixture must reproduce the old 448 MiB failure');
// The increased bound must not affect the generated bytes or simulation.
const previous = require(path.resolve(__dirname, '../work-0380/payload/resources/native/lobby/supcom2-ui.cjs'));
assert.throws(() => previous.readZip(full.result.archive, 4096, true), /Expanded archive exceeds limit/);
assert.throws(() => ui.readZip(full.result.archive, 4096, false), /Archive is too large/);
const invalid = ui.writeZip([{name: '../unsafe', data: Buffer.from('x')}], {compress: true});
assert.throws(() => ui.readZip(invalid, 4096, true), /Unsafe archive name/);
const badCrc = Buffer.from(ui.writeZip([{name: 'valid', data: Buffer.from('x')}]));
badCrc[35] ^= 1;
assert.throws(() => ui.readZip(badCrc, 4096, true), /CRC/);

build('reforged-balance', 2.5, research);
build('vanilla-plus', 1.125, research);
build('vanilla-1.260-iwbp', 1.125);
console.log('Archive regression, custom research, profile isolation, CRC and path guards passed.');
